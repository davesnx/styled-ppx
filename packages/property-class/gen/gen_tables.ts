import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type Coverage = {
  extra: string[];
  checked: string[];
  shorthands: Record<string, string[]>;
};

const here = (path: string): string => fileURLToPath(new URL(path, import.meta.url));

const arg = (flag: string, fallback: string): string => {
  const at = process.argv.indexOf(flag);
  return at >= 0 && process.argv[at + 1] !== undefined ? process.argv[at + 1]! : fallback;
};

const coveragePath = here("../../cx-conformance/coverage.json");
const registryPath = here("registry_names.txt");
const tablePath = here("../core/css_property_table.ml");
const tableOut = arg("--table-out", tablePath);
const coverOut = arg("--cover-out", here("../core/css_cover.ml"));
const dataOut = arg("--data-out", here("../core/css_cover_data.ml"));
const referenceOut = arg("--reference-out", here("../core/test/cover_reference.ml"));

const maxNames = 1295;
const universal = "all";

const coverage = JSON.parse(readFileSync(coveragePath, "utf8")) as Coverage;
const registry = readFileSync(registryPath, "utf8")
  .split("\n")
  .filter((n) => n !== "" && !n.startsWith("--"));

const shorthands = new Map(Object.entries(coverage.shorthands));
const everyName = new Set<string>([
  ...coverage.checked,
  ...coverage.extra,
  ...registry,
  ...shorthands.keys(),
  ...[...shorthands.values()].flat(),
]);

const rank = (name: string): [number, number, string] => [name.startsWith("-") ? 1 : 0, name.length, name];
const compareRank = (a: string, b: string): number => {
  const [x, y] = [rank(a), rank(b)];
  return x[0] - y[0] || x[1] - y[1] || (x[2] < y[2] ? -1 : x[2] > y[2] ? 1 : 0);
};

const aliasOf = new Map<string, string>();
const sameLeaves = new Map<string, string[]>();
for (const [name, leaves] of shorthands) {
  if (leaves.length === 1 && leaves[0] !== name) aliasOf.set(name, leaves[0]!);
  else if (leaves.length > 1) {
    const key = [...leaves].sort().join(",");
    sameLeaves.set(key, [...(sameLeaves.get(key) ?? []), name]);
  }
}
for (const group of sameLeaves.values()) {
  const [canonical, ...rest] = [...group].sort(compareRank);
  for (const name of rest) aliasOf.set(name, canonical!);
}
const canonicalOf = (name: string): string => {
  let seen = name;
  for (let next = aliasOf.get(seen); next !== undefined; next = aliasOf.get(seen)) seen = next;
  return seen;
};

const existing = (existsSync(tablePath) ? readFileSync(tablePath, "utf8") : "")
  .split("\n")
  .flatMap((line) => {
    const m = /^\s*"([^"]+)";?\s*$/.exec(line);
    return m ? [m[1]!] : [];
  });

const canonicalNames = new Set([...everyName].map(canonicalOf));
for (const name of existing) {
  if (!canonicalNames.has(name)) {
    throw new Error(`table row ${JSON.stringify(name)} is no longer a canonical property name; the table is append-only`);
  }
}
const known = new Set(existing);
const names = [...existing, ...[...canonicalNames].filter((n) => !known.has(n)).sort()];
if (names.length > maxNames) throw new Error(`${names.length} names exceed the ${maxNames} two-character ids`);

const indexOf = new Map(names.map((n, i) => [n, i]));
const idx = (name: string): number => indexOf.get(canonicalOf(name))!;

const leaves: number[][] = names.map((name, i) => {
  const set = shorthands.get(name);
  return set ? [...new Set(set.map(idx))].sort((a, b) => a - b) : [i];
});

const parent = names.map((_, i) => i);
const find = (i: number): number => (parent[i] === i ? i : (parent[i] = find(parent[i]!)));
const universalIndex = indexOf.get(universal);
names.forEach((_, i) => {
  if (i === universalIndex) return;
  for (const leaf of leaves[i]!) parent[find(leaf)] = find(i);
});
const familyNumber = new Map<number, number>();
const families = names.map((_, i) => {
  if (i === universalIndex) return 0;
  const root = find(i);
  if (!familyNumber.has(root)) familyNumber.set(root, familyNumber.size + 1);
  return familyNumber.get(root)!;
});

const lookup: [string, number][] = [...everyName]
  .map((n): [string, number] => [n, idx(n)])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const header = "(* Generated by packages/property-class/gen/gen_tables.ts. Do not edit. *)\n\n";
const ocamlString = (s: string): string => JSON.stringify(s);
const intArray = (xs: number[]): string => `[| ${xs.join("; ")} |]`;

const table = `${header}let names =\n  [|\n${names.map((n) => `    ${ocamlString(n)};\n`).join("")}  |]\n`;

const packed = (() => {
  let previousId = 0;
  const entries: string[] = [];
  leaves.forEach((set, i) => {
    if (set.length === 1 && set[0] === i) return;
    let previous = i;
    const deltas = set.map((leaf) => {
      const d = leaf - previous;
      previous = leaf;
      return (d >= 0 ? 2 * d : -2 * d - 1).toString(36);
    });
    entries.push(`${(i - previousId).toString(36)}=${deltas.join(",")}`);
    previousId = i;
  });
  return entries.join(" ");
})();

const data = `${header}let count = ${names.length}
let universal = ${universalIndex}
let packed = ${ocamlString(packed)}
`;

const reference = `${header}let leaf_table : int array array =
  [|
${leaves.map((l) => `    ${intArray(l)};\n`).join("")}  |]

let family_table : int array = ${intArray(families)}
`;

const cover = `${header}let lookup : (string * int) array =
  [|
${lookup.map(([n, i]) => `    (${ocamlString(n)}, ${i});\n`).join("")}  |]

let digit n = if n < 10 then Char.chr (48 + n) else Char.chr (87 + n)
let id_of_index i = String.init 2 (fun k -> digit (if k = 0 then i / 36 else i mod 36))

let id_of_name name =
  let name = String.lowercase_ascii name in
  let rec search lo hi =
    if lo > hi then None
    else
      let mid = (lo + hi) / 2 in
      let key, i = lookup.(mid) in
      let c = String.compare name key in
      if c = 0 then Some (id_of_index i)
      else if c < 0 then search lo (mid - 1)
      else search (mid + 1) hi
  in
  search 0 (Array.length lookup - 1)

let index_of_id id =
  let value c = if c <= '9' then Char.code c - 48 else Char.code c - 87 in
  let is_base36 c = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') in
  if String.length id <> 2 || not (is_base36 id.[0] && is_base36 id.[1]) then -1
  else
    let i = (value id.[0] * 36) + value id.[1] in
    if i < Css_leaves.count then i else -1

let leaves : Css_class_format.prop -> Css_class_format.prop list = function
  | Name _ as p -> [ p ]
  | Id id as p ->
    let i = index_of_id id in
    if i < 0 then [ p ]
    else
      List.map
        (fun j -> Css_class_format.Id (id_of_index j))
        (Array.to_list (Css_leaves.leaf_indices i))

let size : Css_class_format.prop -> int = function
  | Name _ -> 1
  | Id id ->
    let i = index_of_id id in
    if i < 0 then 1 else Array.length (Css_leaves.leaf_indices i)

let family : Css_class_format.prop -> int = function
  | Name _ -> -1
  | Id id ->
    let i = index_of_id id in
    if i < 0 then -1 else Css_leaves.family_of_index i
`;

writeFileSync(tableOut, table);
writeFileSync(coverOut, cover);
writeFileSync(dataOut, data);
writeFileSync(referenceOut, reference);
